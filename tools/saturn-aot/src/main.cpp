namespace {

struct SegmentArgument {
    saturn::core::Address base{};
    std::filesystem::path path;
};

struct ImageVariantArgument {
    std::string name;
    std::vector<SegmentArgument> segments;
};

struct Arguments {
    std::vector<ImageVariantArgument> variants{{"default", {}}};
    std::vector<saturn::core::Address> entries;
    std::vector<std::filesystem::path> entryLists;
    std::filesystem::path output;
    std::filesystem::path outputDirectory;
};

void usage(std::ostream& output) {
    output << "Usage: saturn-aot --segment <base-hex> <binary> "
              "[--segment <base-hex> <binary> ...] "
              "[--variant <name> --segment <base-hex> <binary> ...] "
              "[--entry <address-hex>] [--entry-list <addresses.txt>] "
              "(--output <module.cpp> | --output-dir <directory>)\n"
              "Each variant is a full image; repeat resident segments in overlay variants.\n"
              "Example: saturn-aot --segment 0x06010000 0.BIN --entry 0x06010000 "
              "--output-dir build/rockman-static\n"
              "Use --output for one translation unit or --output-dir for stable "
              "64 KiB address-bank shards.\n";
}

[[nodiscard]] bool writeIfChanged(const std::filesystem::path& path,
                                  std::string_view contents) {
    std::ifstream existing(path, std::ios::binary);
    if (existing) {
        const std::string previous((std::istreambuf_iterator<char>(existing)),
                                   std::istreambuf_iterator<char>());
        if (previous == contents) return true;
    }

    std::error_code error;
    std::filesystem::create_directories(path.parent_path(), error);
    if (error) return false;
    std::ofstream output(path, std::ios::binary | std::ios::trunc);
    if (!output) return false;
    output.write(contents.data(), static_cast<std::streamsize>(contents.size()));
    output.close();
    return static_cast<bool>(output);
}

[[nodiscard]] std::string bankName(std::uint16_t bank) {
    std::ostringstream text;
    text << std::uppercase << std::hex << std::setw(4) << std::setfill('0') << bank;
    return text.str();
}

[[nodiscard]] std::string makeRegistrySource(
    const std::set<std::uint16_t>& banks) {
    std::ostringstream source;
    source << "// Generated by saturnbox-aot. Do not edit.\n"
              "#include \"saturn/sir/static_module.hpp\"\n"
              "#include <cstddef>\n#include <vector>\n\n";
    for (const auto bank : banks) {
        source << "extern \"C\" const ::saturn::sir::StaticNativeBlockEntry* "
               << "saturnbox_static_blocks_" << bankName(bank)
               << "(std::size_t*) noexcept;\n";
    }
    source << "\nextern \"C\" const ::saturn::sir::StaticNativeBlockEntry* "
              "saturnbox_static_blocks(std::size_t* count) noexcept {\n"
              "    using Entry = ::saturn::sir::StaticNativeBlockEntry;\n"
              "    using Getter = const Entry* (*)(std::size_t*) noexcept;\n"
              "    static const std::vector<Entry> entries = [] {\n"
              "        std::vector<Entry> result;\n"
              "        const auto append = [&result](Getter getter) {\n"
              "            std::size_t shardCount{};\n"
              "            const auto* shard = getter(&shardCount);\n"
              "            if (shard != nullptr) result.insert(result.end(), shard, shard + shardCount);\n"
              "        };\n";
    for (const auto bank : banks) {
        source << "        append(&saturnbox_static_blocks_" << bankName(bank) << ");\n";
    }
    source << "        return result;\n"
              "    }();\n"
              "    if (count != nullptr) *count = entries.size();\n"
              "    return entries.data();\n"
              "}\n";
    return source.str();
}

[[nodiscard]] std::string makeCmakeSourceList(
    const std::set<std::uint16_t>& banks) {
    std::ostringstream source;
    source << "# Generated by saturnbox-aot. Do not edit.\n"
              "set(SATURNBOX_GENERATED_STATIC_SOURCES\n"
              "    \"${CMAKE_CURRENT_LIST_DIR}/saturnbox_static_registry.cpp\"\n";
    for (const auto bank : banks) {
        source << "    \"${CMAKE_CURRENT_LIST_DIR}/saturnbox_shard_"
               << bankName(bank) << ".cpp\"\n";
    }
    source << ")\n";
    return source.str();
}

[[nodiscard]] bool emitShardDirectory(
    std::span<const saturn::sir::Module* const> modules,
    const std::filesystem::path& directory,
    saturn::sir::StaticModuleEmitReport& total) {
    std::set<std::uint16_t> banks;
    for (const auto* module : modules) {
        for (const auto& [address, block] : module->blocks()) {
            (void)address;
            if (block->isLowered()) {
                banks.insert(static_cast<std::uint16_t>(block->address() >> 16U));
            }
        }
    }
    if (banks.empty()) {
        total.error = "no lowered blocks to emit";
        return false;
    }

    std::error_code error;
    std::filesystem::create_directories(directory, error);
    if (error) {
        total.error = "unable to create output directory: " + error.message();
        return false;
    }

    const auto manifestPath = directory / "saturnbox_shards.txt";
    std::set<std::string> previousShards;
    {
        std::ifstream manifest(manifestPath);
        std::string line;
        while (std::getline(manifest, line)) {
            if (line.starts_with("saturnbox_shard_") && line.ends_with(".cpp") &&
                line.size() == std::string_view("saturnbox_shard_0000.cpp").size()) {
                previousShards.insert(line);
            }
        }
    }

    std::set<std::string> currentShards;
    for (const auto bank : banks) {
        const auto name = "saturnbox_shard_" + bankName(bank) + ".cpp";
        currentShards.insert(name);
        std::ostringstream source;
        saturn::sir::StaticModuleEmitOptions options;
        options.addressBank = bank;
        const auto symbol = "saturnbox_static_blocks_" + bankName(bank);
        options.registryFunction = symbol;
        const auto emitted = saturn::sir::emitStaticModulesCpp(modules, source, options);
        if (!emitted.success()) {
            total.error = emitted.error;
            return false;
        }
        total.blocksEmitted += emitted.blocksEmitted;
        total.instructionsEmitted += emitted.instructionsEmitted;
        total.skippedBlocks.insert(total.skippedBlocks.end(),
                                   emitted.skippedBlocks.begin(), emitted.skippedBlocks.end());
        if (!writeIfChanged(directory / name, source.str())) {
            total.error = "unable to write generated shard " + name;
            return false;
        }
    }

    for (const auto& staleShard : previousShards) {
        if (!currentShards.contains(staleShard)) {
            std::filesystem::remove(directory / staleShard, error);
            if (error) {
                total.error = "unable to remove stale generated shard " + staleShard;
                return false;
            }
        }
    }

    const auto registry = makeRegistrySource(banks);
    if (!writeIfChanged(directory / "saturnbox_static_registry.cpp", registry) ||
        !writeIfChanged(directory / "saturnbox_sources.cmake", makeCmakeSourceList(banks))) {
        total.error = "unable to write generated shard registry or CMake source list";
        return false;
    }

    std::ostringstream manifest;
    manifest << "# Generated by saturnbox-aot; stable guest address-bank shards.\n";
    for (const auto& shard : currentShards) manifest << shard << '\n';
    if (!writeIfChanged(manifestPath, manifest.str())) {
        total.error = "unable to write shard manifest";
        return false;
    }
    return true;
}

[[nodiscard]] std::optional<saturn::core::Address> parseAddress(std::string_view value) {
    if (value.starts_with("0x") || value.starts_with("0X")) value.remove_prefix(2U);
    if (value.empty()) return std::nullopt;
    std::uint32_t parsed{};
    const auto [end, error] = std::from_chars(value.data(), value.data() + value.size(),
                                               parsed, 16);
    if (error != std::errc{} || end != value.data() + value.size()) return std::nullopt;
    return parsed;
}

[[nodiscard]] std::optional<Arguments> parseArguments(int argc, char** argv) {
    Arguments arguments;
    std::size_t activeVariant{};
    for (int index = 1; index < argc; ++index) {
        const std::string_view option(argv[index]);
        if (option == "--help" || option == "-h") {
            usage(std::cout);
            return std::nullopt;
        }
        if (option == "--segment") {
            if (index + 2 >= argc) return std::nullopt;
            const auto base = parseAddress(argv[++index]);
            if (!base) return std::nullopt;
            arguments.variants[activeVariant].segments.push_back({*base, argv[++index]});
            continue;
        }
        if (option == "--variant") {
            if (index + 1 >= argc) return std::nullopt;
            const std::string name(argv[++index]);
            if (name.empty() || arguments.variants[activeVariant].segments.empty()) {
                std::cerr << "error: each image variant needs a name and at least one segment\n";
                return std::nullopt;
            }
            if (std::any_of(arguments.variants.begin(), arguments.variants.end(),
                [&](const ImageVariantArgument& variant) { return variant.name == name; })) {
                std::cerr << "error: duplicate image variant " << name << '\n';
                return std::nullopt;
            }
            arguments.variants.push_back({name, {}});
            activeVariant = arguments.variants.size() - 1U;
            continue;
        }
        if (option == "--entry") {
            if (index + 1 >= argc) return std::nullopt;
            const auto entry = parseAddress(argv[++index]);
            if (!entry) return std::nullopt;
            arguments.entries.push_back(*entry);
            continue;
        }
        if (option == "--entry-list") {
            if (index + 1 >= argc) return std::nullopt;
            arguments.entryLists.emplace_back(argv[++index]);
            continue;
        }
        if (option == "--output") {
            if (index + 1 >= argc) return std::nullopt;
            arguments.output = argv[++index];
            continue;
        }
        if (option == "--output-dir") {
            if (index + 1 >= argc) return std::nullopt;
            arguments.outputDirectory = argv[++index];
            continue;
        }
        std::cerr << "error: unknown argument " << option << '\n';
        return std::nullopt;
    }
    if (arguments.variants.empty() || arguments.variants.back().segments.empty() ||
        (arguments.entries.empty() && arguments.entryLists.empty()) ||
        (arguments.output.empty() == arguments.outputDirectory.empty())) return std::nullopt;
    return arguments;
}

int run(const Arguments& arguments) {
    std::vector<saturn::core::Address> tracedEntries;
    for (const auto& path : arguments.entryLists) {
        std::ifstream input(path);
        if (!input) {
            std::cerr << "error: unable to read entry list " << path.string() << '\n';
            return 1;
        }
        std::string line;
        while (std::getline(input, line)) {
            const auto first = line.find_first_not_of(" \t\r\n");
            if (first == std::string::npos || line[first] == '#') continue;
            const auto last = line.find_last_not_of(" \t\r\n");
            const auto address = parseAddress(std::string_view(line).substr(first, last - first + 1U));
            if (!address) {
                std::cerr << "error: invalid address in " << path.string() << ": " << line << '\n';
                return 1;
            }
            tracedEntries.push_back(*address);
        }
        if (!input.eof()) {
            std::cerr << "error: failed while reading entry list " << path.string() << '\n';
            return 1;
        }
    }
    std::sort(tracedEntries.begin(), tracedEntries.end());
    tracedEntries.erase(std::unique(tracedEntries.begin(), tracedEntries.end()),
                        tracedEntries.end());

    std::vector<std::unique_ptr<saturn::sir::Module>> ownedModules;
    std::vector<const saturn::sir::Module*> modules;
    std::size_t totalEntries{};
    std::size_t totalCfgBlocks{};
    std::size_t totalLoweredBlocks{};
    std::size_t totalLiftFailures{};
    for (const auto& variant : arguments.variants) {
        saturn::core::MemoryMap image;
        for (const auto& input : variant.segments) {
            const auto segmentImage =
                saturn::core::MemoryMap::fromFile(input.path, input.base);
            if (!segmentImage) {
                std::cerr << "error: unable to read SH-2 segment "
                          << input.path.string() << " in variant " << variant.name << '\n';
                return 1;
            }
            for (const auto& [base, segment] : segmentImage->segments()) {
                if (!image.addSegment(base, segment.bytes)) {
                    std::cerr << "error: overlapping or invalid segment at 0x"
                              << std::hex << base << std::dec << " in variant "
                              << variant.name << '\n';
                    return 1;
                }
            }
        }

        auto entries = arguments.entries;
        for (const auto address : tracedEntries) {
            // One trace may cover several overlay versions. Keep only roots
            // backed by bytes in this complete image variant.
            if (image.contains(address, 2U)) entries.push_back(address);
        }
        entries.erase(std::remove_if(entries.begin(), entries.end(),
            [&](saturn::core::Address address) {
                return !image.contains(address, 2U);
            }), entries.end());
        std::sort(entries.begin(), entries.end());
        entries.erase(std::unique(entries.begin(), entries.end()), entries.end());
        totalEntries += entries.size();

        const auto cfg = saturn::sh2::BlockBuilder{}.build(image, entries);
        auto module = std::make_unique<saturn::sir::Module>();
        const auto lift = saturn::sh2::lowerCFG(cfg, *module);
        totalCfgBlocks += cfg.blocks.size();
        totalLoweredBlocks += lift.loweredBlocks;
        totalLiftFailures += lift.failures.size();
        modules.push_back(module.get());
        ownedModules.push_back(std::move(module));
    }

    saturn::sir::StaticModuleEmitReport emit;
    if (!arguments.outputDirectory.empty()) {
        if (!emitShardDirectory(modules, arguments.outputDirectory, emit)) {
            std::cerr << "error: " << emit.error << '\n';
            return 1;
        }
    } else {
        std::ofstream output(arguments.output, std::ios::binary | std::ios::trunc);
        if (!output) {
            std::cerr << "error: unable to create " << arguments.output.string() << '\n';
            return 1;
        }
        emit = saturn::sir::emitStaticModulesCpp(modules, output);
        output.close();
    }
    if (!emit.success()) {
        std::cerr << "error: " << emit.error << '\n';
        return 1;
    }
    std::size_t totalSegments{};
    for (const auto& variant : arguments.variants) {
        totalSegments += variant.segments.size();
    }
    std::cout << "Static native module source\n"
              << "  image variants: " << arguments.variants.size() << '\n'
              << "  input segments: " << totalSegments << '\n'
              << "  entry points: " << totalEntries << '\n'
              << "  CFG blocks: " << totalCfgBlocks << '\n'
              << "  lowered blocks: " << totalLoweredBlocks << '\n'
              << "  emitted blocks: " << emit.blocksEmitted << '\n'
              << "  emitted SIR instructions: " << emit.instructionsEmitted << '\n'
              << "  skipped blocks: " << emit.skippedBlocks.size() << '\n'
              << "  lift failures: " << totalLiftFailures << '\n'
              << "  output: " << (arguments.outputDirectory.empty()
                    ? arguments.output.string() : arguments.outputDirectory.string()) << '\n';
    if (emit.blocksEmitted == 0U) return 1;
    return 0;
}

} // namespace

int main(int argc, char** argv) {
    const auto arguments = parseArguments(argc, argv);
    if (!arguments) {
        usage(std::cerr);
        return 2;
    }
    return run(*arguments);
}
