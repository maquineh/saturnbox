param(
    [Parameter(Mandatory = $true)]
    [ValidateNotNullOrEmpty()]
    [string[]] $Modules,

    [Parameter(Mandatory = $true)]
    [ValidateNotNullOrEmpty()]
    [string] $OutputDirectory
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

if ($Modules.Count -eq 0) {
    throw 'At least one generated module is required.'
}

$resolvedModules = [System.Collections.Generic.List[string]]::new()
foreach ($module in $Modules) {
    $resolved = (Resolve-Path -LiteralPath $module -ErrorAction Stop).Path
    if (-not (Test-Path -LiteralPath $resolved -PathType Leaf)) {
        throw "Module is not a file: $resolved"
    }
    $resolvedModules.Add($resolved)
}

$outputPath = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($OutputDirectory)
if (Test-Path -LiteralPath $outputPath) {
    throw "Output directory already exists; refusing to overwrite it: $outputPath"
}

$parent = [System.IO.Path]::GetDirectoryName($outputPath)
if (-not [string]::IsNullOrEmpty($parent) -and
    -not (Test-Path -LiteralPath $parent -PathType Container)) {
    throw "Output parent directory does not exist: $parent"
}

$getterPattern = '(?m)^(?<prefix>\s*extern\s+"C"\s+const\s+::saturn::sir::StaticNativeBlockEntry\*\s*)saturnbox_static_blocks(?<suffix>\s*\(\s*std::size_t\s*\*\s*count\s*\)\s*noexcept\s*\{)'
$preparedModules = [System.Collections.Generic.List[object]]::new()
$symbolRegex = [System.Text.RegularExpressions.Regex]::new('\bsaturnbox_static_blocks\b')
foreach ($sourcePath in $resolvedModules) {
    $contents = [System.IO.File]::ReadAllText($sourcePath)
    $getterMatches = [System.Text.RegularExpressions.Regex]::Matches(
        $contents, $getterPattern)
    $symbolMatches = $symbolRegex.Matches($contents)
    if ($getterMatches.Count -ne 1 -or $symbolMatches.Count -ne 1) {
        throw "Expected exactly one generated saturnbox_static_blocks getter in '$sourcePath'; found getter=$($getterMatches.Count), symbol=$($symbolMatches.Count)."
    }
    $preparedModules.Add([pscustomobject]@{
        sourcePath = $sourcePath
        contents = $contents
        getter = $getterMatches[0]
    })
}

$null = New-Item -ItemType Directory -Path $outputPath

$moduleNames = [System.Collections.Generic.List[string]]::new()
$manifestModules = [System.Collections.Generic.List[object]]::new()
$sourceFiles = [System.Collections.Generic.List[string]]::new()

for ($index = 0; $index -lt $preparedModules.Count; $index++) {
    $prepared = $preparedModules[$index]
    $sourcePath = $prepared.sourcePath
    $moduleName = 'saturnbox_static_blocks_module_{0:D3}' -f $index
    $moduleNames.Add($moduleName)
    $match = $prepared.getter
    $replacement = $match.Groups['prefix'].Value + $moduleName +
        $match.Groups['suffix'].Value
    $contents = $prepared.contents
    $rewritten = $contents.Substring(0, $match.Index) + $replacement +
        $contents.Substring($match.Index + $match.Length)

    $fileName = 'module_{0:D3}.cpp' -f $index
    $destination = Join-Path $outputPath $fileName
    [System.IO.File]::WriteAllText(
        $destination, $rewritten, [System.Text.UTF8Encoding]::new($false))
    $sourceFiles.Add('    "${CMAKE_CURRENT_LIST_DIR}/' + $fileName + '"')

    $manifestModules.Add([ordered]@{
        index = $index
        sourcePath = $sourcePath
        sourceSha256 = (Get-FileHash -LiteralPath $sourcePath -Algorithm SHA256).Hash.ToLowerInvariant()
        outputPath = $fileName
        outputSha256 = (Get-FileHash -LiteralPath $destination -Algorithm SHA256).Hash.ToLowerInvariant()
        registryGetter = $moduleName
    })
}

$aggregator = @'
// Generated by merge_x4_aot.ps1. Keep distinct SIR signatures at reused guest addresses.
#include "saturn/sir/static_module.hpp"
#include <algorithm>
#include <cstddef>
#include <vector>

'@
foreach ($moduleName in $moduleNames) {
    $aggregator += @"
extern "C" const ::saturn::sir::StaticNativeBlockEntry* $moduleName(std::size_t*) noexcept;
"@
}
$aggregator += @'

extern "C" const ::saturn::sir::StaticNativeBlockEntry*
saturnbox_static_blocks(std::size_t* count) noexcept {
    using Entry = ::saturn::sir::StaticNativeBlockEntry;
    using Getter = const Entry* (*)(std::size_t*) noexcept;
    static const std::vector<Entry> entries = [] {
        std::vector<Entry> merged;
        const auto append = [&merged](Getter getter) {
            std::size_t moduleCount{};
            const auto* moduleEntries = getter(&moduleCount);
            if (moduleEntries != nullptr && moduleCount != 0U) {
                merged.insert(merged.end(), moduleEntries, moduleEntries + moduleCount);
            }
        };
'@
foreach ($moduleName in $moduleNames) {
    $aggregator += "        append(&$moduleName);`n"
}
$aggregator += @'
        std::stable_sort(merged.begin(), merged.end(),
            [](const Entry& left, const Entry& right) {
                if (left.address != right.address) return left.address < right.address;
                if (left.signature.first != right.signature.first)
                    return left.signature.first < right.signature.first;
                return left.signature.second < right.signature.second;
            });
        merged.erase(std::unique(merged.begin(), merged.end(),
            [](const Entry& left, const Entry& right) {
                return left.address == right.address &&
                       left.signature == right.signature;
            }), merged.end());
        return merged;
    }();
    if (count != nullptr) *count = entries.size();
    return entries.data();
}
'@

$aggregatorPath = Join-Path $outputPath 'saturnbox_static_aggregator.cpp'
[System.IO.File]::WriteAllText(
    $aggregatorPath, $aggregator, [System.Text.UTF8Encoding]::new($false))
$sourceFiles.Add('    "${CMAKE_CURRENT_LIST_DIR}/saturnbox_static_aggregator.cpp"')

$cmake = [System.Collections.Generic.List[string]]::new()
$cmake.Add('# Generated by merge_x4_aot.ps1. Do not edit.')
$cmake.Add('set(SATURNBOX_GENERATED_STATIC_SOURCES')
foreach ($sourceFile in $sourceFiles) { $cmake.Add($sourceFile) }
$cmake.Add(')')
$cmakePath = Join-Path $outputPath 'saturnbox_sources.cmake'
[System.IO.File]::WriteAllLines(
    $cmakePath, $cmake.ToArray(), [System.Text.UTF8Encoding]::new($false))

$manifest = [ordered]@{
    generator = 'merge_x4_aot.ps1'
    registryGetter = 'saturnbox_static_blocks'
    modules = @($manifestModules)
    aggregatorPath = 'saturnbox_static_aggregator.cpp'
    aggregatorSha256 = (Get-FileHash -LiteralPath $aggregatorPath -Algorithm SHA256).Hash.ToLowerInvariant()
    cmakeSourceListPath = 'saturnbox_sources.cmake'
    cmakeSourceListSha256 = (Get-FileHash -LiteralPath $cmakePath -Algorithm SHA256).Hash.ToLowerInvariant()
}
$manifestPath = Join-Path $outputPath 'manifest.json'
$manifestJson = ConvertTo-Json -InputObject $manifest -Depth 5
[System.IO.File]::WriteAllText(
    $manifestPath, $manifestJson + [Environment]::NewLine,
    [System.Text.UTF8Encoding]::new($false))

Write-Output "Merged $($resolvedModules.Count) generated module(s) into $outputPath"
Write-Output "CMake source list: $cmakePath"
Write-Output "Manifest: $manifestPath"
